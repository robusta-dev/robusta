from typing import Any, Dict, Optional

from hikaru.model.rel_1_26 import Deployment, DeploymentCondition

from robusta.core.playbooks.base_trigger import TriggerEvent
from robusta.integrations.kubernetes.autogenerated.triggers import DeploymentChangeEvent, DeploymentUpdateTrigger
from robusta.integrations.kubernetes.base_triggers import K8sTriggerEvent
from robusta.utils.scope import ScopeParams

NEW_RS_AVAILABLE_REASON = "NewReplicaSetAvailable"
TIMED_OUT_REASON = "ProgressDeadlineExceeded"


def get_progressing_condition(deployment: Optional[Deployment]) -> Optional[DeploymentCondition]:
    if not deployment or not deployment.status or not deployment.status.conditions:
        return None
    return next((c for c in deployment.status.conditions if c.type == "Progressing"), None)


def _is_spec_observed(deployment: Deployment) -> bool:
    return (deployment.status.observedGeneration or 0) >= (deployment.metadata.generation or 0)


def is_rollout_complete_transition(deployment: Deployment, old_deployment: Optional[Deployment]) -> bool:
    """True on the one update in which a rollout finishes.

    The controller sets Progressing to NewReplicaSetAvailable, naming the new ReplicaSet in the
    message, only when a rollout completes; scaling and informer resyncs leave it untouched.
    Deployments with progressDeadlineSeconds disabled have no Progressing condition and never fire.
    """
    condition = get_progressing_condition(deployment)
    if condition is None or condition.reason != NEW_RS_AVAILABLE_REASON or not _is_spec_observed(deployment):
        return False
    old_condition = get_progressing_condition(old_deployment)
    return not (
        old_condition
        and old_condition.reason == NEW_RS_AVAILABLE_REASON
        and old_condition.message == condition.message
    )


def is_rollout_failure_transition(deployment: Deployment, old_deployment: Optional[Deployment]) -> bool:
    """True on the update in which a rollout exceeds its progressDeadlineSeconds."""
    condition = get_progressing_condition(deployment)
    if condition is None or condition.reason != TIMED_OUT_REASON:
        return False
    old_condition = get_progressing_condition(old_deployment)
    return not (
        old_condition and old_condition.reason == TIMED_OUT_REASON and old_condition.message == condition.message
    )


class _DeploymentRolloutTrigger(DeploymentUpdateTrigger):
    def __init__(
        self,
        name_prefix: str = None,
        namespace_prefix: str = None,
        labels_selector: str = None,
        scope: ScopeParams = None,
    ):
        super().__init__(
            name_prefix=name_prefix,
            namespace_prefix=namespace_prefix,
            labels_selector=labels_selector,
            scope=scope,
        )

    @staticmethod
    def is_transition(deployment: Deployment, old_deployment: Optional[Deployment]) -> bool:
        raise NotImplementedError

    def should_fire(self, event: TriggerEvent, playbook_id: str, build_context: Dict[str, Any]):
        if not super().should_fire(event, playbook_id, build_context):
            return False

        if not isinstance(event, K8sTriggerEvent):
            return False

        exec_event = self.build_execution_event(event, {}, build_context)
        if not isinstance(exec_event, DeploymentChangeEvent):
            return False

        return self.is_transition(exec_event.obj, exec_event.old_obj)


class DeploymentRolloutCompleteTrigger(_DeploymentRolloutTrigger):
    """
    Fires once when a Deployment rollout completes: every replica runs the new pod template and is available.
    """

    @staticmethod
    def is_transition(deployment: Deployment, old_deployment: Optional[Deployment]) -> bool:
        return is_rollout_complete_transition(deployment, old_deployment)


class DeploymentRolloutFailureTrigger(_DeploymentRolloutTrigger):
    """
    Fires once when a Deployment rollout fails to make progress within its progressDeadlineSeconds.
    """

    @staticmethod
    def is_transition(deployment: Deployment, old_deployment: Optional[Deployment]) -> bool:
        return is_rollout_failure_transition(deployment, old_deployment)
