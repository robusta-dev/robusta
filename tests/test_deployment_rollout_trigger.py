import copy
import json
from pathlib import Path
from typing import List, Optional

import pytest

from robusta.core.playbooks.trigger import Trigger
from robusta.core.triggers.deployment_rollout_trigger import (
    DeploymentRolloutCompleteTrigger,
    DeploymentRolloutFailureTrigger,
)
from robusta.integrations.kubernetes.autogenerated.events import DeploymentChangeEvent
from robusta.integrations.kubernetes.base_triggers import IncomingK8sEventPayload, K8sTriggerEvent

# A real `kubectl get deploy -w --output-watch-events -o json` stream (k3s v1.31, progressDeadlineSeconds: 30)
# of one Deployment going through: create (rollout to busybox:1.36.1) -> image update to 1.37.0 -> scale 2->4 ->
# scale 4->2 -> image update to a tag that doesn't exist (times out) -> `kubectl rollout undo`.
WATCH_FIXTURE = Path(__file__).parent / "file_fixtures" / "deployment_rollout_watch.jsonl"
# The same Deployment, fully rolled out, then `kubectl rollout pause` + `kubectl rollout resume`.
PAUSE_RESUME_FIXTURE = Path(__file__).parent / "file_fixtures" / "deployment_pause_resume_watch.jsonl"

INITIAL_ROLLOUT_COMPLETE = 6
IMAGE_ROLLOUT_COMPLETE = 15
BAD_ROLLOUT_TIMED_OUT = 29
ROLLBACK_COMPLETE = 33

OPERATIONS = {"ADDED": "create", "MODIFIED": "update", "DELETED": "delete"}


def load_watch(path: Path = WATCH_FIXTURE) -> List[dict]:
    with open(path) as f:
        return [json.loads(line) for line in f]


def make_trigger_event(obj: dict, old_obj: Optional[dict], operation: str) -> K8sTriggerEvent:
    return K8sTriggerEvent(
        k8s_payload=IncomingK8sEventPayload(
            operation=operation,
            kind="Deployment",
            apiVersion="apps/v1",
            clusterUid="test-cluster",
            description=f"Deployment {obj['metadata']['name']} {operation}d",
            obj=copy.deepcopy(obj),
            oldObj=copy.deepcopy(old_obj) if old_obj else None,
        )
    )


def fired_indices(trigger, watch: List[dict]) -> List[int]:
    fired = []
    previous = None
    for i, watch_event in enumerate(watch):
        event = make_trigger_event(watch_event["object"], previous, OPERATIONS[watch_event["type"]])
        if trigger.should_fire(event, "playbook-id", {}):
            fired.append(i)
        previous = watch_event["object"]
    return fired


def without_progressing_condition(watch: List[dict]) -> List[dict]:
    watch = copy.deepcopy(watch)
    for watch_event in watch:
        status = watch_event["object"].get("status", {})
        status["conditions"] = [c for c in status.get("conditions", []) if c["type"] != "Progressing"]
    return watch


@pytest.fixture(scope="module")
def watch() -> List[dict]:
    return load_watch()


def test_fixture_matches_the_recorded_scenario(watch):
    def progressing_reason(i):
        conditions = watch[i]["object"]["status"]["conditions"]
        return next(c["reason"] for c in conditions if c["type"] == "Progressing")

    assert progressing_reason(INITIAL_ROLLOUT_COMPLETE) == "NewReplicaSetAvailable"
    assert progressing_reason(IMAGE_ROLLOUT_COMPLETE) == "NewReplicaSetAvailable"
    assert progressing_reason(BAD_ROLLOUT_TIMED_OUT) == "ProgressDeadlineExceeded"
    assert progressing_reason(ROLLBACK_COMPLETE) == "NewReplicaSetAvailable"


def test_rollout_complete_fires_once_per_rollout_and_not_on_scaling(watch):
    assert fired_indices(DeploymentRolloutCompleteTrigger(), watch) == [
        INITIAL_ROLLOUT_COMPLETE,
        IMAGE_ROLLOUT_COMPLETE,
        ROLLBACK_COMPLETE,
    ]


def test_rollout_failure_fires_once_when_the_deadline_is_exceeded(watch):
    assert fired_indices(DeploymentRolloutFailureTrigger(), watch) == [BAD_ROLLOUT_TIMED_OUT]


def test_pause_and_resume_without_a_new_template_does_not_fire():
    pause_resume = load_watch(PAUSE_RESUME_FIXTURE)
    reasons = [
        next(c["reason"] for c in e["object"]["status"]["conditions"] if c["type"] == "Progressing")
        for e in pause_resume
    ]
    assert "DeploymentResumed" in reasons and reasons[-1] == "NewReplicaSetAvailable"
    assert fired_indices(DeploymentRolloutCompleteTrigger(), pause_resume) == []


def test_resumed_mid_rollout_still_fires(watch):
    # paused while old pods still ran: completing after the resume is a real rollout
    completed = watch[IMAGE_ROLLOUT_COMPLETE]["object"]
    resumed = copy.deepcopy(watch[IMAGE_ROLLOUT_COMPLETE - 1]["object"])
    progressing = next(c for c in resumed["status"]["conditions"] if c["type"] == "Progressing")
    progressing.update(reason="DeploymentResumed", message="Deployment is resumed")
    assert DeploymentRolloutCompleteTrigger().should_fire(make_trigger_event(completed, resumed, "update"), "id", {})


@pytest.mark.parametrize(
    "trigger,index,expected",
    [
        (
            DeploymentRolloutCompleteTrigger(),
            IMAGE_ROLLOUT_COMPLETE,
            "Rollout of Deployment `checkout-api` in namespace `rollout-fixture` completed",
        ),
        (
            DeploymentRolloutFailureTrigger(),
            BAD_ROLLOUT_TIMED_OUT,
            "Rollout of Deployment `checkout-api` in namespace `rollout-fixture` failed",
        ),
    ],
)
def test_description_names_the_outcome(watch, trigger, index, expected):
    event = make_trigger_event(watch[index]["object"], watch[index - 1]["object"], "update")
    assert trigger.build_execution_event(event, {}, {}).description == expected


def test_resync_with_identical_objects_does_not_fire(watch):
    completed = watch[IMAGE_ROLLOUT_COMPLETE]["object"]
    timed_out = watch[BAD_ROLLOUT_TIMED_OUT]["object"]
    assert not DeploymentRolloutCompleteTrigger().should_fire(
        make_trigger_event(completed, completed, "update"), "playbook-id", {}
    )
    assert not DeploymentRolloutFailureTrigger().should_fire(
        make_trigger_event(timed_out, timed_out, "update"), "playbook-id", {}
    )


def test_without_progressing_condition_never_fires(watch):
    # progressDeadlineSeconds disabled: replica counts alone can't tell a rollout from scaling
    assert fired_indices(DeploymentRolloutCompleteTrigger(), without_progressing_condition(watch)) == []
    assert fired_indices(DeploymentRolloutFailureTrigger(), without_progressing_condition(watch)) == []


def test_trigger_filters_still_apply(watch):
    assert fired_indices(DeploymentRolloutCompleteTrigger(namespace_prefix="payments"), watch) == []
    assert fired_indices(DeploymentRolloutCompleteTrigger(name_prefix="checkout"), watch) == [
        INITIAL_ROLLOUT_COMPLETE,
        IMAGE_ROLLOUT_COMPLETE,
        ROLLBACK_COMPLETE,
    ]
    assert fired_indices(DeploymentRolloutCompleteTrigger(labels_selector="app=other"), watch) == []


def test_ignores_other_kinds(watch):
    obj = copy.deepcopy(watch[IMAGE_ROLLOUT_COMPLETE]["object"])
    old_obj = copy.deepcopy(watch[IMAGE_ROLLOUT_COMPLETE - 1]["object"])
    event = make_trigger_event(obj, old_obj, "update")
    event.k8s_payload.kind = "StatefulSet"
    assert not DeploymentRolloutCompleteTrigger().should_fire(event, "playbook-id", {})


@pytest.mark.parametrize(
    "trigger_name,trigger_class",
    [
        ("on_deployment_rollout_complete", DeploymentRolloutCompleteTrigger),
        ("on_deployment_rollout_failure", DeploymentRolloutFailureTrigger),
    ],
)
def test_triggers_load_from_playbook_config(trigger_name, trigger_class):
    trigger = Trigger(**{trigger_name: {"namespace_prefix": "payments"}}).get()
    assert isinstance(trigger, trigger_class)
    assert trigger.namespace_prefix == "payments"
    assert trigger.get_execution_event_type() is DeploymentChangeEvent
