import json

import hikaru
from hikaru.model.rel_1_26 import Deployment

from robusta.core.model.k8s_operation_type import K8sOperationType
from robusta.core.reporting import FindingSource
from robusta.integrations.kubernetes.autogenerated.events import KubernetesAnyChangeEvent


def _deployment() -> Deployment:
    with open("tests/k8s_change_obj.json") as f:
        return hikaru.from_dict(json.loads(f.read()), Deployment)


def test_default_finding_keeps_the_subject_of_the_changed_object():
    obj = _deployment()
    event = KubernetesAnyChangeEvent(operation=K8sOperationType.UPDATE, obj=obj, old_obj=obj)

    finding = event.create_default_finding()

    assert finding.aggregation_key == "GenericChange"
    assert finding.source == FindingSource.KUBERNETES_API_SERVER
    assert finding.subject.name == obj.metadata.name
    assert finding.subject.namespace == obj.metadata.namespace
    assert finding.attribute_map["namespace"] == obj.metadata.namespace


def test_default_finding_without_object_does_not_fail():
    event = KubernetesAnyChangeEvent(operation=K8sOperationType.DELETE)

    finding = event.create_default_finding()

    assert finding.title == "Kubernetes delete"
    assert finding.source == FindingSource.KUBERNETES_API_SERVER
    assert finding.subject.name == "Unresolved"
